class Peer:
    """A tiny Whisper Transcription Manager substitute that records what it gets."""

    def __init__(self):
        self.replies: dict[str, object] = {}
        self.calls: list[dict] = []
        self.server = None
        self.thread = None

    def set_value(self, path: str, answer, code: int = 200):
        self.replies[path] = (answer, code)

    @property
    def base_url(self) -> str:
        return f"http://127.0.0.1:{self.server.server_address[1]}"

    def start(self):
        outside = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass  # don't litter test output

            def _find(self, path):
                """Exact first, then prefix — a pattern with `*` at the end
                catches everything under it (e.g., `/api/jobs/*`)."""
                only = path.split("?")[0]
                if only in outside.replies:
                    return outside.replies[only]
                for pattern, value in outside.replies.items():
                    if pattern.endswith("*") and only.startswith(pattern[:-1]):
                        return value
                return None

            def _reply(self, hits, path, method, body=None):
                outside.calls.append(
                    {"method": method, "path": path, "body": body, "header": dict(self.headers)}
                )
                if hits is None:
                    self.send_response(404)
                    self.send_header("Content-Type", "application/json")
                    self.end_headers()
                    self.wfile.write(b'{"error": "not found"}')
                    return
                answer, code = hits
                if callable(answer):
                    answer = answer(path, body)
                data = json.dumps(answer).encode()
                self.send_response(code)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def do_GET(self):
                self._reply(self._find(self.path), self.path, "GET")

            def do_POST(self):
                n = int(self.headers.get("Content-Length") or 0)
                raw = self.rfile.read(n) if n else b""
                kind = self.headers.get("Content-Type") or ""
                if kind.startswith("application/json"):
                    try:
                        body = json.loads(raw or b"{}")
                    except ValueError:
                        body = {"__raw__": raw[:200].decode("latin1")}
                else:
                    # multipart (upload): just remember the length, that's enough
                    body = {"__multipart_bytes__": len(raw)}
                self._reply(self._find(self.path), self.path, "POST", body)

        self.server = HTTPServer(("127.0.0.1", 0), Handler)
        # A short poll: shutdown() waits for it, half a second by default
        self.thread = threading.Thread(
            target=self.server.serve_forever, kwargs={"poll_interval": 0.02}, daemon=True
        )
        self.thread.start()
        return self

    def stop(self):
        if self.server:
            self.server.shutdown()
            self.server.server_close()


