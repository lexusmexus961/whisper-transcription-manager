class TestUpload:
    def test_a_file_is_uploaded_in_parts(self, app, mcp_tools, tmp_path):
        q = tmp_path / "sample.mp4"
        q.write_bytes(b"x" * (mcp.CHUNK * 2 + 10))  # three parts
        app.set_value(
            "/api/upload_chunk",
            lambda p, k: (
                {
                    "status": "complete",
                    "filename": "uploads/sample.mp4",
                    "display_name": "sample.mp4",
                    "directory": "/media/uploads",
                }
            ),
        )
        d = mcp_tools.upload_file(path=str(q))
        assert d["file"] == "uploads/sample.mp4"
        assert d["chunks"] == 3
        assert len([a for a in app.calls if a["path"] == "/api/upload_chunk"]) == 3

    def test_base64_works_too(self, app, mcp_tools):
        import base64

        app.set_value(
            "/api/upload_chunk",
            {"status": "complete", "filename": "uploads/a.opus", "display_name": "a.opus"},
        )
        d = mcp_tools.upload_file(content_base64=base64.b64encode(b"hello").decode(), name="a.opus")
        assert d["file"] == "uploads/a.opus" and d["bytes"] == 5

    def test_without_a_name_no_base64_upload(self, app, mcp_tools):
        import base64

        with pytest.raises(Exception, match="name"):
            mcp_tools.upload_file(content_base64=base64.b64encode(b"x").decode())

    def test_a_file_outside_the_library_is_an_ERROR(self, app, mcp_tools, tmp_path):
        """`filename: null` means: uploaded, but not queueable. Reporting
        that as success with an empty field would be the worse response —
        the caller would think everything was fine."""
        q = tmp_path / "a.mp4"
        q.write_bytes(b"x")
        app.set_value(
            "/api/upload_chunk", {"status": "complete", "filename": None, "directory": "/elsewhere"}
        )
        with pytest.raises(Exception, match="outside the media"):
            mcp_tools.upload_file(path=str(q))

    def test_a_missing_file_is_reported_clearly(self, app, mcp_tools, tmp_path):
        with pytest.raises(Exception, match="No file at"):
            mcp_tools.upload_file(path=str(tmp_path / "does-not-exist.mp4"))


class TestTranscribe:
    def test_the_job_id_matches_the_one_in_the_queue(self):
        """Both formulas side by side. If the one in `core/queue.py`
        changes, the MCP server loses sight of every running job."""
        import hashlib
        from pathlib import Path

        q = (Path(__file__).resolve().parent.parent / "whisper_tm" / "core" / "queue.py").read_text(
            encoding="utf-8"
        )
        assert 'replace(" ", "_").replace(".", "_").replace("/", "_")' in q, (
            "the queue builds the job ID differently than assumed here"
        )
        for name in ("a.mkv", "videos/Archive/x y.mp4", "folder/below/z.opus"):
            safe = name.replace(" ", "_").replace(".", "_").replace("/", "_")
            expected = f"{safe}_{hashlib.sha256(name.encode()).hexdigest()[:8]}"
            assert mcp.job_label(name) == expected

    def test_unset_settings_are_NOT_sent(self, app, mcp_tools):
        """The trap: `_normalize` fills in missing values from the config. A
        preemptively sent false overrides the user's default."""
        app.set_value("/api/queue/add", {"ok": True, "added": 1, "skipped": 0})
        app.set_value("/api/settings", {"dirs": {"media": "/mnt/media"}})
        mcp_tools.transcribe(file="a.mkv", wait=False)
        body = app.calls[-1]["body"]
        # base_dir belongs to it — it is not a transcription SETTING,
        # but the root against which the filename is resolved.
        assert set(body) == {"filenames", "front", "base_dir"}, body


class TestMediaRoot:
    """The root belongs to the entry, not to the moment of execution.

    The hazard: queued files with an empty `base_dir`. An empty `base_dir`
    means "whichever root currently applies" — and that changes the moment
    someone browses to a different folder in the web UI. The entire list
    then fails within a second as "not found", even though every file sits
    untouched on disk.

    A queue row outlives the moment of its creation by hours. What it
    means must be written into it.
    """

    def test_the_root_is_pinned_when_enqueueing(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value("/api/settings", {"dirs": {"media": "/mnt/media"}})
        mcp_tools.transcribe(file="videos/a.mkv", wait=False)
        assert app.calls[-1]["body"]["base_dir"] == "/mnt/media"

    def test_for_the_batch_too(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 2})
        app.set_value("/api/settings", {"dirs": {"media": "/mnt/media"}})
        mcp_tools.transcribe_many(files=["a.mkv", "b.mkv"])
        assert app.calls[-1]["body"]["base_dir"] == "/mnt/media"

    def test_without_information_better_no_base_dir_at_all(self, app, mcp_tools):
        """An empty string would not be "unknown", but exactly the
        state that triggered the incident."""
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        # /api/settings does not respond — the counterpart doesn't know the path.
        mcp_tools.transcribe(file="a.mkv", wait=False)
        assert "base_dir" not in app.calls[-1]["body"]

    def test_the_root_is_fetched_fresh_not_remembered(self, app, mcp_tools):
        """It may change between two calls — if it were remembered it
        would be wrong at exactly the moment it matters."""
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value("/api/settings", {"dirs": {"media": "/mnt/a"}})
        mcp_tools.transcribe(file="x.mkv", wait=False)
        app.set_value("/api/settings", {"dirs": {"media": "/mnt/b"}})
        mcp_tools.transcribe(file="x.mkv", wait=False)
        assert app.calls[-1]["body"]["base_dir"] == "/mnt/b"

    def test_ONLY_the_root_is_read_from_the_answer(self, app, mcp_tools):
        """/api/settings also carries credentials. None of that may end up
        in a tool's result."""
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value(
            "/api/settings",
            {
                "dirs": {"media": "/mnt/media"},
                "config": {
                    "llm": {"api_key": "sk-SECRET-123"},
                    "transcription": {"hf_token": "hf_SECRET"},
                },
            },
        )
        d = mcp_tools.transcribe(file="a.mkv", wait=False)
        assert "SECRET" not in json.dumps(d)
        assert app.calls[-1]["body"]["base_dir"] == "/mnt/media"

    def test_the_settings_that_were_set_arrive(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        mcp_tools.transcribe(
            file="a.mkv", wait=False, language="de", model="large-v3", diarize=True, num_speakers=3
        )
        k = app.calls[-1]["body"]
        assert k["language"] == "de" and k["model"] == "large-v3"
        assert k["diarize"] is True and k["numSpeakers"] == 3

    def test_a_file_that_was_not_enqueued_is_explained(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 0, "skipped": 1})
        with pytest.raises(Exception, match="was not queued"):
            mcp_tools.transcribe(file="foreign.mkv", wait=False)

    def test_with_waiting_the_transcript_comes_back(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value("/api/jobs/*", {"status": "done", "jobId": "x"})
        app.set_value(
            "/api/transcript/a.mkv",
            {
                "language": "de",
                "model": "large-v3",
                "total_duration": "00:01:00",
                "segments": [
                    {"start": 0.0, "end": 2.0, "speaker": "SPEAKER_00", "text": "Hello world"}
                ],
            },
        )
        d = mcp_tools.transcribe(file="a.mkv", wait=True, timeout_min=1)
        assert d["done"] is True
        assert d["text"] == "SPEAKER_00: Hello world"
        assert d["segments"] == 1

    def test_a_time_limit_cancels_NOTHING(self, app, mcp_tools):
        """It only ends the wait. A client timeout must never destroy a
        running transcription."""
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value("/api/jobs/*", {"status": "processing", "progress": 30})
        d = mcp_tools.transcribe(file="long.mkv", wait=True, timeout_min=1)
        # No cancel call was made
        assert not [a for a in app.calls if "cancel" in a["path"]]
        assert d["done"] is False
        assert d["job_id"] == mcp.job_label("long.mkv")
        assert "CONTINUES" in d["note"]

    def test_a_failed_job_becomes_an_error(self, app, mcp_tools):
        app.set_value("/api/queue/add", {"ok": True, "added": 1})
        app.set_value("/api/jobs/*", {"status": "error", "error": "no audio"})
        with pytest.raises(Exception, match="no audio"):
            mcp_tools.transcribe(file="still.mkv", wait=True, timeout_min=1)


