"""The MCP server — making the library accessible to an AI.

Purpose: an MCP server built with FastMCP, so a local AI assistant can use
the app — e.g. transcribe a video; the important parts are uploading files
and YouTube videos.

The server runs as its own process and speaks the HTTP API of the app. These
tests present it with a **real** HTTP counterpart — an
``http.server.HTTPServer`` with handler in thread, like ``test_llm_client.py``
demonstrates. There's no ``requests-mock`` in the project, and a handwritten
opponent checks more: it sees what really goes over the line.

The pitfalls held here:

* **Unset settings must not be sent along.**
  ``core/queue.py:_normalize`` fills in missing from config; a preemptively
  sent ``false`` still overrides the user's set default.
* **The job ID is calculated in advance** — otherwise you couldn't
  track a job before the queue starts it. It must match the one
  generated by ``core/queue.py``; both formulas stand side by side here.
* **A time limit breaks nothing.** It only ends the wait. The
  difference between "the client gave up" and "the transcription is
  lost".
* **An upload without rel_path is an error**, not success with empty field:
  The file then lies outside the library and is not queueable.
"""

