def _sent(app) -> dict:
    from urllib.parse import parse_qs, urlsplit

    return parse_qs(urlsplit(app.calls[-1]["path"]).query)


def _moments(o, path="") -> list[str]:
    """Where a tool's answer has a start: Ask makes each such dict a
    playable reference (core/chat.Refs.tag), with the file of the dict
    around it when it has none of its own."""
    found = []
    if isinstance(o, dict):
        if "start_sec" in o or "start" in o:
            found.append(path)
        for k, v in o.items():
            found += _moments(v, f"{path}.{k}")
    elif isinstance(o, list):
        for i, v in enumerate(o):
            found += _moments(v, f"{path}[{i}]")
    return found


