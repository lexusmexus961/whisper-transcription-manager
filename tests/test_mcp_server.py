class TestCommandLine:
    """The calls documented in every guide must actually exist.

    A former incident: ``--stdio`` was documented everywhere — in the plan,
    in the settings tab, in the client config — but never defined as an
    argument; stdio was only the default when NOTHING is given. The first
    startup attempt therefore ended with ``unrecognized arguments: --stdio``,
    and that before anything else could have gone well or badly.

    Only the parser is checked here: it must not settle the calls with a
    SystemExit. Actually starting the server would only test the
    fastmcp library.
    """

    def _parse(self, argv):
        """Only up to the parsed namespace — no connection setup."""
        import argparse
        import inspect

        source = inspect.getsource(mcp.main)
        # Extract the parser setup out of main(): everything up to the
        # parse_args line. This keeps the test tied to the real
        # definition instead of to a copy that drifts apart.
        i = source.index("p = argparse.ArgumentParser(")
        j = source.index("a = p.parse_args(")
        body = inspect.cleandoc(source[i:j])
        space = {"argparse": argparse}
        exec(body, space)  # noqa: S102
        return space["p"].parse_args(argv)

    def test_stdio_is_accepted(self):
        a = self._parse(["--stdio"])
        assert a.stdio and not a.http

    def test_without_a_flag_it_is_stdio_as_well(self):
        a = self._parse([])
        assert not a.http

    def test_http_is_accepted(self):
        a = self._parse(["--http", "--port", "5399"])
        assert a.http and a.port == 5399

    def test_both_transports_at_once_are_an_error(self):
        """Otherwise one of the two would silently win — and the user
        looks for the server on a port it never listened on."""
        with pytest.raises(SystemExit):
            self._parse(["--stdio", "--http"])

    def test_every_documented_switch_exists(self):
        a = self._parse(["--base", "http://x:1", "--token", "t", "--read-only", "--check"])
        assert a.base == "http://x:1" and a.token == "t"
        assert a.read_only and a.check


class TestEnglishSurface:
    """What goes over the protocol is English — and stays that way.

    On the other end hangs a language model that decides which tool to use
    based on the names and descriptions. The models are trained on English
    for that; a German name in the middle of an otherwise English list is
    exactly the kind of break that leads to "the tool was never called".

    Only the outer surface is checked here — tool names, parameters, return
    fields: the parts a model reads.
    """

    #: Words that don't exist in English and that in practice are the
    #: first to slip through. No dictionary check — that would constantly
    #: misfire on technical terms.
    GERMAN = (
        "datei",
        "sprech",
        "spricht",
        "sprach",
        "stimme",
        "warten",
        "zeit",
        "suche",
        "personen",
        "werkzeug",
        "hinweis",
        "fehler",
        "einstell",
        "transkri",
        "uebersetz",
        "zusammen",
        "loesch",
        "gesamt",
        "schwelle",
        "auftrag",
        "ergebnis",
        "kennung",
        "anzahl",
        "bestand",
        "aufnahme",
        "wurzel",
        "gefunden",
        "verzeichnis",
        "geschnitten",
        "eingereiht",
        "liste",
        # The second row comes from the app's pass-through blocks —
        # exactly the ones that went unnoticed on the first attempt.
        "ohne",
        "dauer",
        "groesse",
        "woerter",
        "zeichen",
        "fassung",
        "betriebspunkt",
        "modelle",
        "stimmen",
        "indiziert",
        "wert",
        "rechenzeit",
    )

    def _suspicious(self, word: str) -> list[str]:
        w = word.lower()
        # `file`/`files` contains no German word; `file` does.
        return [d for d in self.GERMAN if d in w]

    def test_the_tool_names_are_english(self):
        import asyncio

        server = mcp.build_server()
        for t in asyncio.run(server.list_tools()):
            assert not self._suspicious(t.name), t.name

    def test_the_parameter_names_are_english(self):
        import asyncio

        server = mcp.build_server()
        for t in asyncio.run(server.list_tools()):
            for p in (t.parameters or {}).get("properties", {}):
                assert not self._suspicious(p), f"{t.name}({p})"

    def test_the_descriptions_are_english(self):
        """A German description works exactly like a German name."""
        import asyncio

        server = mcp.build_server()
        # A single foreign word may appear as a QUOTE — the name of a
        # template, say. So look for German function words instead: those
        # are never a quote.
        stop = (
            " der ",
            " die ",
            " das ",
            " und ",
            " nicht ",
            " eine ",
            " wird ",
            " werden ",
            " kann ",
            " nur ",
        )
        for t in asyncio.run(server.list_tools()):
            text = f" {(t.description or '').lower()} "
            hits = [s for s in stop if s in text]
            assert not hits, f"{t.name}: {hits}"

    def _deep(self, o, path="") -> list[str]:
        """Check every key in the WHOLE tree, not just at the top.

        The first version only looked at the top level — and directly
        underneath sat the app's pass-through blocks (`without_audio`, `duration`,
        `operating_point`, `label`). A half-translated structure is worse
        for a model than a consistently German one.
        """
        hits = []
        if isinstance(o, dict):
            for k, v in o.items():
                if self._suspicious(str(k)):
                    hits.append(f"{path}{k}")
                hits += self._deep(v, f"{path}{k}.")
        elif isinstance(o, list) and o:
            hits += self._deep(o[0], f"{path}[].")
        return hits

