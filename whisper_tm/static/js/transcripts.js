// ── Delete: first ask WHAT ───────────────────────────────────────────────
// Since derivatives survive deleting the transcript, "delete" is no longer
// a yes/no question. The dialog only offers what actually exists.
let _delFile = null;

async function deleteTx(filename) {
    _delFile = filename;
    document.getElementById('delFilename').textContent = filename;
    const opt = document.getElementById('delOptions');
    opt.innerHTML = '<div class="hint">Loading…</div>';
    document.getElementById('btnDelGo').disabled = true;
    document.getElementById('delModal').classList.add('visible');

    let d = {};
    try {
        const r = await fetch('/api/derivatives/' + encodeURIComponent(filename));
        d = await r.json();
    } catch (e) { d = {}; }
    if (_delFile !== filename) return;   // User clicked on to something else

    const line = (value, label, hint, preset) => `
        <div class="field">
            <label style="display:flex;align-items:center;gap:8px;cursor:pointer;text-transform:none;font-size:0.85rem">
                <input type="checkbox" value="${value}" ${preset ? 'checked' : ''}
                       style="width:16px;height:16px;accent-color:var(--red)">
                ${label}
            </label>
            <div class="hint">${hint}</div>
        </div>`;

    let html = '';
    if (d.transcript) {
        html += line('transcript', '📄 Transcript',
                      'Segments, speakers, timestamps — and the transcript file alongside it.', true);
    }
    if (d.summaries) {
        html += line('summaries', `🤖 Summaries (${d.summaries})`,
                      'Generated by the LLM. Regenerating costs compute time again.', false);
    }
    if (d.translations) {
        html += line('translations', `🌐 Translations (${d.translations})`,
                      'All language versions of this file.', false);
    }
    if (d.edits) {
        html += line('edits', `🪄 Correction runs (${d.edits})`,
                      'Saved suggestions from LLM correction.', false);
    }
    if (!html) {
        opt.innerHTML = '<div class="hint">Nothing is stored for this file that could be deleted.</div>';
        return;
    }
    opt.innerHTML = html;
    document.getElementById('btnDelGo').disabled = false;
}

function closeDelModal() {
    document.getElementById('delModal').classList.remove('visible');
    _delFile = null;
}

async function confirmDelete() {
    const filename = _delFile;
    if (!filename) return;
    const what = [...document.querySelectorAll('#delOptions input[type=checkbox]:checked')]
        .map(c => c.value);
    if (!what.length) {
        if (typeof Toast !== 'undefined') Toast.error('Nothing selected');
        return;
    }
    closeDelModal();
    try {
        const r = await fetch('/api/delete_transcript', {
            method: 'POST',
            headers: {'Content-Type': 'application/json'},
            body: JSON.stringify({filename, what})
        });
        if (!r.ok) throw new Error(`HTTP ${r.status}`);
    } catch(e) {
        if (typeof Toast !== 'undefined') Toast.error('Delete failed'); else alert('Delete failed');
        return;
    }

    const f = fileByName(filename);
    if (f && what.includes('transcript')) {
        f.status = 'pending';
        f.processing_time = '';
        f.audio_duration = '';
    }
    // What's left over decides the derivatives badge — better to ask again
    // than to infer from the selection (the server also cleans up the
    // sidecars).
    if (f) {
        try {
            const remainder = await (await fetch('/api/derivatives/'
                + encodeURIComponent(filename))).json();
            const remaining = (remainder.summaries || 0) + (remainder.translations || 0)
                + (remainder.edits || 0);
            if (remaining && !remainder.transcript) f.has_deriv = true;
            else delete f.has_deriv;
        } catch (e) { delete f.has_deriv; }
        filesChanged();
    }
    // Rebuild the view: depending on the case, derivatives may still remain.
    if (activeFile === filename) {
        activeTranscript = null;
        if (f) selectFile(f);
        else document.getElementById('transcriptArea').innerHTML =
            '<div class="empty-state"><div class="icon">📝</div><p>Deleted</p></div>';
    }
    updateCounts();
    renderFileList();
}

async function deleteSelectedTranscripts() {
    const toDelete = [...selectedFiles].filter(name => {
        const f = fileByName(name);
        const status = f ? f.status : selectionStatus.get(name);
        return status === 'done' || status === 'partial';
    });
    if (toDelete.length === 0) return;
    if (!confirm(`Delete ${toDelete.length} transcript${toDelete.length !== 1 ? 's' : ''}?`)) return;

    // In chunks through the bulk endpoint — before, one request per file in
    // sequence: Ctrl+A selects the whole filter (100k files), and that ran
    // 100k serial requests without any feedback. A toast shows the progress.
    const CHUNK = 500;
    let failed = 0;
    const progress = (toDelete.length > CHUNK && typeof Toast !== 'undefined')
        ? Toast.info(`Deleting ${toDelete.length.toLocaleString()} transcripts …`, 0) : null;
    for (let i = 0; i < toDelete.length; i += CHUNK) {
        const chunk = toDelete.slice(i, i + CHUNK);
        try {
            const r = await fetch('/api/delete_all_transcripts', {
                method: 'POST',
                headers: {'Content-Type': 'application/json'},
                body: JSON.stringify({confirm_token: 'DELETE_ALL_CONFIRMED', filenames: chunk})
            });
            const d = await r.json().catch(() => ({}));
            if (!r.ok || d.error) { failed += chunk.length; continue; }
        } catch(e) { failed += chunk.length; continue; }
        for (const filename of chunk) {
            const f = fileByName(filename);
            if (f) {
                f.status = 'pending';
                f.processing_time = '';
                f.audio_duration = '';
                f.tx_word_count = 0;
                f.tx_date = 0;
            }
            if (activeFile === filename) {
                activeTranscript = null;
            }
        }
        filesChanged();
        const span = progress?.children?.[1];
        if (span) {
            span.textContent = `Deleting transcripts … ${Math.min(i + CHUNK, toDelete.length).toLocaleString()}`
                + ` of ${toDelete.length.toLocaleString()}`;
        }
    }
    if (progress) progress.remove();
    if (failed > 0 && typeof Toast !== 'undefined') {
        Toast.error(`${failed} of ${plural(toDelete.length, 'deletion')} failed`);
    }
    if (activeFile && toDelete.includes(activeFile)) {
        document.getElementById('transcriptArea').innerHTML =
            '<div class="empty-state"><div class="icon">📝</div><p>Transcript deleted</p></div>';
    }
    selectedFiles.clear();
    lastClickedFile = null;
    updateSelectionUI();
    updateCounts();
    renderFileList();
}


async function deleteFilteredTranscripts() {
    // "All filtered" is resolved by the server (the client list has only been
    // a window since pagination was added): fetch the names of the
    // done/orphan rows in the active filter.
    let filenames = [];
    try {
        if (activeTab === 'done' || activeTab === 'orphan') {
            filenames = (await fetchFilteredNames()).names;
        } else {
            const d = await fetchFilteredNames();
            filenames = d.names.filter((n, i) =>
                d.status[i] === 'done' || d.status[i] === 'orphan');
        }
    } catch (e) {
        if (typeof Toast !== 'undefined') Toast.error('Filter resolution failed'); else alert('Filter resolution failed');
        return;
    }
    const doneCount = filenames.length;
    if (doneCount === 0) {
        if (typeof Toast !== 'undefined') Toast.warn('No transcripts in the current filter to delete.'); else alert('No transcripts in the current filter to delete.');
        return;
    }

    const filterHint = document.getElementById('fileFilter').value.trim();
    const filterInfo = filterHint ? ` (Filter: "${filterHint}")` : '';

    // Confirmation 1
    if (!confirm(`⚠️ WARNING!\n\n${doneCount} transcript${doneCount > 1 ? 's' : ''} will be irrevocably deleted!${filterInfo}\n\nProceed?`)) return;

    // Confirmation 2
    if (!confirm(`🔴 SECOND CONFIRMATION\n\nAre you REALLY sure?\n${doneCount} transcript${doneCount > 1 ? 's' : ''} will be DELETED.${filterInfo}\nThis action CANNOT be undone!`)) return;

    // Wait 5 seconds
    const waitModal = document.createElement('div');
    waitModal.id = 'deleteWaitModal';
    waitModal.style.cssText = 'position:fixed;inset:0;z-index:9999;background:rgba(0,0,0,0.7);display:flex;align-items:center;justify-content:center';
    waitModal.innerHTML = `
        <div style="background:var(--bg-1);border:2px solid var(--red);border-radius:12px;padding:30px 40px;text-align:center;max-width:420px">
            <div style="font-size:2rem;margin-bottom:12px">⏳</div>
            <div style="font-size:0.95rem;font-weight:600;color:var(--red);margin-bottom:8px">Final confirmation in...</div>
            <div id="deleteCountdown" style="font-size:2.5rem;font-weight:700;color:var(--tx-1)">5</div>
            <div style="font-size:0.72rem;color:var(--tx-3);margin-top:8px">${plural(doneCount, 'transcript')}${filterInfo}</div>
            <button onclick="document.getElementById('deleteWaitModal').remove()" style="margin-top:16px;padding:6px 20px;background:var(--bg-3);border:1px solid var(--border);border-radius:6px;color:var(--tx-1);cursor:pointer">Cancel</button>
        </div>
    `;
    document.body.appendChild(waitModal);

    let remaining = 5;
    const countdownEl = waitModal.querySelector('#deleteCountdown');
    const proceed = await new Promise(resolve => {
        const timer = setInterval(() => {
            remaining--;
            if (!document.body.contains(waitModal)) {
                clearInterval(timer);
                resolve(false);
                return;
            }
            countdownEl.textContent = remaining;
            if (remaining <= 0) {
                clearInterval(timer);
                resolve(true);
            }
        }, 1000);
    });

    if (!document.body.contains(waitModal)) return;
    waitModal.remove();
    if (!proceed) return;

    // Confirmation 3
    if (!confirm(`🛑 FINAL WARNING!\n\nPermanently delete ${doneCount} transcript${doneCount === 1 ? "" : "s"}?${filterInfo}\n\nThis is the last chance to cancel!`)) return;

    // Execute — send filtered filenames
    let data;
    try {
        const r = await fetch('/api/delete_all_transcripts', {
            method: 'POST',
            headers: {'Content-Type': 'application/json'},
            body: JSON.stringify({confirm_token: 'DELETE_ALL_CONFIRMED', filenames})
        });
        data = await r.json();
    } catch(e) {
        // Network/parse error → otherwise the UI hangs on an open promise
        if (typeof Toast !== 'undefined') Toast.error('Delete failed'); else alert('Delete failed');
        return;
    }
    if (data.error) {
        if (typeof Toast !== 'undefined') Toast.error(data.error); else alert(data.error);
        return;
    }
    if (typeof Toast !== 'undefined') Toast.success(plural(data.deleted, 'transcript') + ' deleted'); else alert(plural(data.deleted, 'transcript') + ' deleted');
    scanFiles();
}

