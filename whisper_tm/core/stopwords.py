_BY_LANGUAGE: dict[str, set[str]] = {
    "de": STOPWORDS_DE,
    "en": STOPWORDS_EN,
}


def _word_pattern() -> re.Pattern:
    """Letter sequences of every script, with the combining marks Indic
    and other scripts write their vowels with. Digits and punctuation are
    excluded — timestamps and numbers are useless for a topic list.

    [a-zA-ZÀ-ž] gave a Russian, Greek or Hindi library no word at all,
    and letters alone (\\w) cut "नमस्ते" at its vowel signs."""
    import unicodedata

    marks, start, prev = [], None, None
    for c in range(0x300, 0x10000):
        if unicodedata.category(chr(c))[0] == "M":
            if start is None:
                start = c
            prev = c
        elif start is not None:
            marks.append(f"\\u{start:04x}-\\u{prev:04x}")
            start = None
    return re.compile(r"[^\W\d_](?:[^\W\d_]|[" + "".join(marks) + "])*")


WORD_PATTERN = _word_pattern()

MIN_WORD_LENGTH = 3


def stopwords(languages: list[str] | None = None) -> set[str]:
    """Combined stopword set for the selected languages."""
    if not languages:
        return set()
    result: set[str] = set()
    for short_code in languages:
        result |= _BY_LANGUAGE.get(str(short_code).lower().strip(), set())
    return result


def words(text: str, stop: set[str]) -> list[str]:
    """Break text into filtered lowercase words.

    Order is preserved because bigram formation depends on adjacency.
    Stopwords are removed without replacement — "the house by the lake"
    becomes ["house", "lake"], so the bigram is "house lake". This is intentional:
    otherwise almost all bigrams would consist of articles.
    """
    if not text:
        return []
    return [
        w
        for w in (m.lower() for m in WORD_PATTERN.findall(text))
        if len(w) >= MIN_WORD_LENGTH and w not in stop
    ]
